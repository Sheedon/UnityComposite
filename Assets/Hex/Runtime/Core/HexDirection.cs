namespace Sheedon.Hex
{
    /**
     * 六边形的六个方向枚举，按稳定顺序定义各个方向，便于遍历、旋转和邻接计算。
     */
    public enum HexDirection
    {
        /**
         * 东北方向。
         */
        NE = 0,

        /**
         * 东方向。
         */
        E = 1,

        /**
         * 东南方向。
         */
        SE = 2,

        /**
         * 西南方向。
         */
        SW = 3,

        /**
         * 西方向。
         */
        W = 4,

        /**
         * 西北方向。
         */
        NW = 5
    }
}